test('SEO: metadatos únicos, canonical y JSON-LD', async ({ page, request }) => {
  await page.goto('/pcs/pc-001-ryzen-5-5600g')
  await expect(page).toHaveTitle('PC Gamer Ryzen 5 5600G (PC-001) | GUGLIELMINI')
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', /\/pcs\/pc-001-ryzen-5-5600g$/)
  const ld = await page.locator('script[type="application/ld+json"]').allTextContents()
  expect(ld.some((t) => t.includes('"@type":"Product"'))).toBe(true)
  const sitemap = await (await request.get('/sitemap.xml')).text()
  expect(sitemap).toContain('/guias/como-probamos-un-pc')
})

test('cada sección tiene su propio menú local y sus sub-páginas', async ({ page }) => {
  await page.goto('/pcs/pc-001-ryzen-5-5600g')
  const local = page.getByRole('navigation', { name: 'Sección PC-001' })
  await expect(local.getByRole('link', { name: 'Resumen' })).toHaveAttribute('aria-current', 'page')
  await local.getByRole('link', { name: 'Especificaciones' }).click()
  await expect(page).toHaveURL(/\/especificaciones$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Especificaciones')
  await expect(page.getByText('ASUS PRIME A520M-K')).toBeVisible()
  await local.getByRole('link', { name: 'Rendimiento' }).click()
  await expect(page).toHaveURL(/\/rendimiento$/)
  await expect(page.getByRole('heading', { name: 'Valorant' })).toBeVisible()

  await page.goto('/services')
  const svc = page.getByRole('navigation', { name: 'Sección Servicios' })
  await svc.getByRole('link', { name: 'Mantenimiento de PC' }).click()
  await expect(page).toHaveURL(/\/services\/mantenimiento$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Mantenimiento de PC')
  await expect(page.getByText('Desde $19.990').first()).toBeVisible()
  const href = decodeURIComponent((await page.getByRole('link', { name: /Consultar por WhatsApp/ }).getAttribute('href')) ?? '')
  expect(href).toContain('servicio de mantenimiento de PC')
})

test('proceso: elegir una etapa cambia el panel (pestañas con teclado)', async ({ page }) => {
  await page.goto('/proceso-armado')
  const tabs = page.getByRole('tab')
  await expect(tabs).toHaveCount(6)
  await tabs.nth(4).click()
  await expect(page.getByRole('tabpanel')).toContainText('Etapa 5 de 6')
  await expect(page.getByRole('tabpanel')).toContainText('MemTest86')
  await page.keyboard.press('End')
  await expect(tabs.nth(5)).toHaveAttribute('aria-selected', 'true')
  await expect(tabs.nth(5)).toBeFocused()
  await expect(page.getByRole('button', { name: 'Siguiente etapa' })).toBeDisabled()
})
