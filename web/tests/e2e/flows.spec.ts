import { expect, test } from '@playwright/test'

test('la portada presenta el equipo y lleva a su ficha', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Armado. Probado. Explicado.')
  await page.getByRole('link', { name: 'Ver el PC-001' }).click()
  await expect(page).toHaveURL(/\/pcs\/pc-001-ryzen-5-5600g$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('PC Gamer Ryzen 5 5600G')
})

test('la galería cambia de foto con clic y con flechas del teclado', async ({ page }) => {
  await page.goto('/pcs/pc-001-ryzen-5-5600g')
  const thumbs = page.getByRole('list', { name: 'Fotografías del equipo' }).getByRole('button')
  await expect(thumbs.first()).toHaveAttribute('aria-pressed', 'true')
  await thumbs.nth(2).click()
  await expect(thumbs.nth(2)).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('ArrowRight')
  await expect(thumbs.nth(3)).toHaveAttribute('aria-pressed', 'true')
  await expect(thumbs.nth(3)).toBeFocused()
})

test('carrito: agregar, persistir, total y mensaje de WhatsApp, quitar', async ({ page }) => {
  await page.goto('/pcs/pc-001-ryzen-5-5600g')
  await page.getByRole('button', { name: 'Agregar al carrito' }).click()
  await expect(page.getByRole('link', { name: /Carrito, 1 equipo/ })).toBeVisible()
  await page.reload()
  await page.getByRole('link', { name: 'En tu carrito, revisar' }).click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.getByText('$700.000').last()).toBeVisible()
  const wa = page.getByRole('link', { name: /Continuar por WhatsApp/ })
  const href = decodeURIComponent((await wa.getAttribute('href')) ?? '')
  expect(href).toContain('https://wa.me/56900000000')
  expect(href).toContain('PC-001 — PC Gamer Ryzen 5 5600G')
  await page.getByRole('button', { name: /Quitar/ }).click()
  await expect(page.getByRole('heading', { name: 'Tu carrito está vacío.' })).toBeVisible()
})

test('catálogo: búsqueda, estado vacío y URL compartible', async ({ page }) => {
  await page.goto('/pcs')
  await page.locator('form[data-ready]').waitFor()
  const search = page.getByRole('searchbox', { name: 'Buscar por modelo o componente' })
  await search.fill('ryzen')
  await expect(page.getByText('1 equipo con estos filtros')).toBeVisible()
  await expect(page).toHaveURL(/q=ryzen/)
  await search.fill('rtx 5090')
  await expect(page.getByRole('heading', { name: 'No hay equipos que coincidan.' })).toBeVisible()
  await page.getByRole('button', { name: 'Quitar filtros' }).click()
  await expect(page.getByText('1 equipo publicado', { exact: true })).toBeVisible()
  await page.goto('/pcs?q=nvme')
  await expect(search).toHaveValue('nvme')
})

